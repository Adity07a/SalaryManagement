"""Idempotently seed 10,000 synthetic employees into PostgreSQL."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from app.core.database import SessionLocal
from app.models import Employee, ExchangeRate, Salary
from app.seed_data import (
    SEED_EMAIL_DOMAIN,
    SEED_EMPLOYEE_COUNT,
    SeedData,
    generate_seed_data,
)
from sqlalchemy import func, select
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.orm import Session

BATCH_SIZE = 1_000

SEED_EMAIL_PATTERN = f"employee%@{SEED_EMAIL_DOMAIN}"


def _execute_in_batches(
    session: Session,
    statement: Any,
    rows: Sequence[dict[str, object]],
) -> None:
    """Execute bulk inserts in controlled batches."""

    for start in range(0, len(rows), BATCH_SIZE):
        batch = rows[start : start + BATCH_SIZE]

        session.execute(statement, batch)


def persist_seed_data(
    session: Session,
    data: SeedData,
) -> tuple[int, int]:
    """Persist generated employees, salary history and exchange rates.

    Employee and salary records are inserted only when their unique
    keys do not already exist.

    Existing employee details and salary history are never overwritten.
    Seed exchange rates are maintained at their declared static values.
    """

    # -------------------------------------------------
    # 1. Insert or update exchange rates.
    # Exchange rates must exist before salary records
    # because salaries reference exchange_rates.currency.
    # -------------------------------------------------

    rate_insert = pg_insert(ExchangeRate.__table__).values(data.exchange_rates)

    rate_upsert = rate_insert.on_conflict_do_update(
        index_elements=[ExchangeRate.currency],
        set_={"rate_to_base": rate_insert.excluded.rate_to_base},
    )

    session.execute(rate_upsert)

    # -------------------------------------------------
    # 2. Insert employees.
    # Duplicate emails are ignored on subsequent runs.
    # -------------------------------------------------

    employee_insert = pg_insert(Employee.__table__).on_conflict_do_nothing(
        index_elements=[Employee.email]
    )

    _execute_in_batches(
        session,
        employee_insert,
        data.employees,
    )

    # -------------------------------------------------
    # 3. Retrieve database employee IDs.
    # Salary records require actual employee IDs,
    # which are generated by PostgreSQL.
    # -------------------------------------------------

    seeded_employee_rows = session.execute(
        select(
            Employee.id,
            Employee.email,
        ).where(Employee.email.like(SEED_EMAIL_PATTERN))
    ).all()

    employee_id_by_email = {
        email: employee_id for employee_id, email in seeded_employee_rows
    }

    if len(employee_id_by_email) != len(data.employees):
        raise RuntimeError(
            "Seed verification failed: expected exactly "
            f"{len(data.employees)} seeded employees, found "
            f"{len(employee_id_by_email)}."
        )

    # -------------------------------------------------
    # 4. Prepare salary records.
    # -------------------------------------------------

    salary_rows: list[dict[str, object]] = []

    for salary in data.salaries:
        employee_email = salary["employee_email"]

        employee_id = employee_id_by_email.get(employee_email)

        if employee_id is None:
            raise RuntimeError(f"No employee found for {employee_email}.")

        salary_rows.append(
            {
                "employee_id": employee_id,
                "amount": salary["amount"],
                "currency": salary["currency"],
                "effective_from": salary["effective_from"],
            }
        )

    # -------------------------------------------------
    # 5. Insert salary history.
    # A duplicate employee/effective date is ignored.
    # This makes repeated execution idempotent.
    # -------------------------------------------------

    salary_insert = pg_insert(Salary.__table__).on_conflict_do_nothing(
        index_elements=[
            Salary.employee_id,
            Salary.effective_from,
        ]
    )

    _execute_in_batches(
        session,
        salary_insert,
        salary_rows,
    )

    # -------------------------------------------------
    # 6. Verify inserted records.
    # Every seeded employee must have at least one salary.
    # -------------------------------------------------

    employee_count = session.scalar(
        select(func.count())
        .select_from(Employee)
        .where(Employee.email.like(SEED_EMAIL_PATTERN))
    )

    salary_count = session.scalar(
        select(func.count())
        .select_from(Salary)
        .join(
            Employee,
            Employee.id == Salary.employee_id,
        )
        .where(Employee.email.like(SEED_EMAIL_PATTERN))
    )

    missing_salary_exists = (
        select(Salary.id).where(Salary.employee_id == Employee.id).exists()
    )

    employees_without_salary = session.scalar(
        select(func.count())
        .select_from(Employee)
        .where(
            Employee.email.like(SEED_EMAIL_PATTERN),
            ~missing_salary_exists,
        )
    )

    if employees_without_salary:
        raise RuntimeError(
            f"Seed verification failed: "
            f"{employees_without_salary} employees "
            "do not have a salary record."
        )

    return (
        int(employee_count or 0),
        int(salary_count or 0),
    )


def main() -> None:
    """Generate and persist the complete seed dataset."""

    data = generate_seed_data()

    if len(data.employees) != SEED_EMPLOYEE_COUNT:
        raise RuntimeError("Seed generator did not produce exactly 10,000 employees.")

    # A single transaction ensures that either all seed
    # operations succeed or the entire operation rolls back.
    with SessionLocal.begin() as session:
        employee_count, salary_count = persist_seed_data(
            session,
            data,
        )

    print("Salary Management seed completed successfully.")

    print(f"Seeded employees: {employee_count:,}")

    print(f"Seeded salary records: {salary_count:,}")

    print(f"Exchange rates: {len(data.exchange_rates)}")


if __name__ == "__main__":
    main()
